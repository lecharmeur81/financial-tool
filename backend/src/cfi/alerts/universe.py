"""Versioned parameters and fixed vocabulary for Alerts (Phase 23 spec; ADR-0035, ADR-0071).

Implements the alert architecture ADR-0035 already decided (ARCHITECTURE.md §5.19) rather than
redesigning it: rule-based alerts on L1-L4 and data-quality events only, never on AI text; the
``usr.alert_event`` table name; hysteresis/cooldown/deduplication; in-app delivery first.

Reuses ``cfi.analyst.universe.DOMAIN_TOOL_IDS`` for the alert-type-to-tool mapping (R13: no
parallel identification scheme) and its ``BANNED_PATTERNS``/``INSUFFICIENT_DATA_PHRASE`` for the
same no-trading-directive, no-fabricated-certainty discipline applied to any free text an alert
record carries (``trigger_condition``, labels) — this phase adds no new banned-language patterns
of its own because alerts carry no prose generated by an LLM; the reused patterns simply guard the
hand-written template strings in ``cfi.alerts.rules`` against ever drifting into directive
language (CLAUDE.md A1, Phase 23 spec "Severity").
"""

from __future__ import annotations

from datetime import timedelta

from cfi.analyst.universe import BANNED_PATTERNS, DOMAIN_TOOL_IDS

__all__ = [
    "ALERT_SCHEMA_VERSION",
    "ALERT_TYPE_TOOL_IDS",
    "BANNED_PATTERNS",
    "COOLDOWN_PARAMETERS",
    "HIGH_CONFIDENCE_REGIME_THRESHOLD",
    "SEVERITY_LEVELS",
    "STATUS_VALUES",
]

ALERT_SCHEMA_VERSION = "alert_event.v1"

# --------------------------------------------------------------------------- alert types
# (Phase 23 spec "Scope": 11 distinct monitored domains map to exactly 11 alert types. "Exchange
# flows" is deliberately folded into "whale_activity" rather than kept as its own 12th type: both
# read the same single tool (``get_whale_activity``) and the same underlying on-chain exchange-flow
# dataset — ``cfi.analyst.universe.KNOWN_PLATFORM_LIMITATIONS`` already discloses this platform has
# no aggregate exchange-wallet flow independent of whale flow data (Phase 19). Treating them as two
# types would not add a second, independent signal — it would duplicate one.)
ALERT_TYPE_TOOL_IDS: dict[str, str] = {
    "institutional_flow": DOMAIN_TOOL_IDS["institutional"],
    "whale_activity": DOMAIN_TOOL_IDS["whale"],  # covers "Whale activity" and "Exchange flows"
    "retail_activity": DOMAIN_TOOL_IDS["retail"],
    "derivatives": DOMAIN_TOOL_IDS["derivatives"],
    "liquidity": DOMAIN_TOOL_IDS["liquidity"],
    "macro": DOMAIN_TOOL_IDS["macro"],
    "market_structure": DOMAIN_TOOL_IDS["market_structure"],
    "divergence": DOMAIN_TOOL_IDS["divergences"],
    "anomaly": DOMAIN_TOOL_IDS["anomalies"],
    "capital_rotation": DOMAIN_TOOL_IDS["capital_rotation"],
    "regime_change": "get_market_regime",  # not in DOMAIN_TOOL_IDS: Phase 21 cites it directly,
    # never through the 10-domain structure (ADR-0069) — same tool_id, reused by name.
}

# --------------------------------------------------------------------------- severity
# ("Severity" section: describes significance of the detected event, never a trading
# recommendation. Deliberately NOT ranked across the 7 score-bearing domains' own band vocabulary
# (each domain defines its own band labels independently, e.g. derivatives' "low/moderate/elevated/
# high stress" vs. institutional's differently-worded bands) — inventing a cross-domain severity
# ranking over label text this phase does not own would itself be fabricating an interpretation
# (R3). Severity is instead assigned only where this phase can point to an existing, already-
# disclosed closed vocabulary or threshold: "critical" for anomaly's known extreme bands, "notable"
# as the uniform default elsewhere, and "elevated" for a regime change the regime engine itself
# reports with high confidence (see HIGH_CONFIDENCE_REGIME_THRESHOLD below).)
SEVERITY_LEVELS: tuple[str, ...] = ("info", "notable", "elevated", "critical")

# A declared policy threshold (not a data-fitted one, R4) for when a regime-change alert is
# reported as "elevated" rather than the uniform "notable" default — the regime engine's own
# confidence score, already computed and disclosed (Phase 14), crossing a round, published cutoff.
HIGH_CONFIDENCE_REGIME_THRESHOLD = "0.70"

# --------------------------------------------------------------------------- lifecycle
# ("Persistence": "active, acknowledged, resolved, expired, or equivalent states".)
STATUS_VALUES: tuple[str, ...] = ("active", "acknowledged", "resolved", "expired")

# --------------------------------------------------------------------------- cooldown
# ("Deduplication / Cooldown": a declared, disclosed policy constant, not fitted to any one
# metric's own distribution (R4) — mirrors the posture of every other *_parameters module in this
# codebase (e.g. ``cfi.anomaly.universe.AnomalyBandParameters``): a single, versioned, published
# cooldown window applied uniformly across every alert type, long enough that the periodic sweep
# (every 15 minutes, see ``cfi.worker.schedule.alert_entries``) cannot re-fire the same re-armed
# condition within the same evaluation cycle, short enough that a genuinely new development is
# never silenced for long.)
COOLDOWN_PARAMETERS: dict[str, timedelta] = {"alert_cooldown.v1": timedelta(hours=1)}
CURRENT_COOLDOWN_VERSION = "alert_cooldown.v1"


def cooldown_period() -> timedelta:
    return COOLDOWN_PARAMETERS[CURRENT_COOLDOWN_VERSION]
