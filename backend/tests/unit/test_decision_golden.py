@pytest.mark.parametrize(
    (
        "fid",
        "scope",
        "codes",
        "ctx",
        "final",
        "pre",
        "conf",
        "posture",
        "conflict",
        "risks",
        "rules",
    ),
    GOLDEN,
    ids=[g[0] for g in GOLDEN],
)
def test_golden_fixture(
    fid: str,
    scope: str,
    codes: list[str],
    ctx: dict[str, Any],
    final: str,
    pre: str,
    conf: str,
    posture: str,
    conflict: bool,
    risks: tuple[str, ...],
    rules: tuple[str, ...],
) -> None:
    result = assess(make_payload(codes, scope=scope, **ctx), scope)
    assert result.final_stance == Stance(final), fid
    assert result.directional_stance_before_limits == Stance(pre), fid
    assert result.confidence == Confidence(conf), fid
    assert result.posture == Posture(posture), fid
    assert result.conflict is conflict, fid
    assert tuple(r.level for r in result.risks) == tuple(RiskLevel(x) for x in risks), fid
    for rule in rules:
        assert rule in result.fired_rule_ids, (fid, rule)
    assert result.methodology_version == "decision_methodology.v0"
    assert result.parameter_version == "decision_params.v0"
    assert result.template_version == "decision_templates.v0"


def test_golden_set_has_the_thirty_numbered_fixtures() -> None:
    ids = {g[0] for g in GOLDEN}
    assert {f"F-{i}" for i in range(1, 31) if i != 24} <= ids
    assert {"F-24a", "F-24b"} <= ids
    assert len(GOLDEN) == 31


def test_f12_exact_fifty_percent_coverage_classifies() -> None:
    """Exactly 50% coverage cannot occur in a five-domain scope; the four-domain scope exercises
    the boundary: 2 of 4 classifies (the floor is c < 1/2), 1 of 4 does not."""
    on_floor = assess(make_payload(["S1", "S1", "U", "U"], scope="SOL"), "SOL")
    below = assess(make_payload(["S1", "U", "U", "U"], scope="SOL"), "SOL")
    assert on_floor.final_stance is Stance.CAUTIOUSLY_BULLISH
    assert below.final_stance is Stance.INSUFFICIENT
    assert DEFAULT_ACTIVITY  # builders share the same default vocabulary
